//===========================================================================================
void Pi_Calc(Tpi * pi, float Ref, float Input)
{
	
    pi->Err = Ref - Input;																				// ошибка регулирования
		//pi->Err = ApplyDeadzone( pi->Err );														// зона чувствительности
		//pi->Err = ApplyHysteresis( pi->Err );													// гистерезис
    pi->Up = pi->Kp * pi->Err;																		// пропорциональная составляющая
		pi->Ui = pi->Ui + pi->Ki * pi->Err;														// интегральная составляющая
		// ограничитель интегральной составляющей
    if (pi->Ui > pi->OutMax)		pi->Ui = pi->OutMax;
    else 
    if (pi->Ui < pi->OutMin)		pi->Ui = pi->OutMin;	
		    
    pi->Ud = pi->Kd * (pi->Err - pi->PrevErr);								// Дифференциальная составляющая
		pi->PrevErr = pi->Err;  																	// Сохраняем текущую ошибку для следующего расчета
	
    pi->Output = pi->Up + pi->Ui + pi->Ud;										// сумма составляющих

		// ограничитель
    if (pi->Output > pi->OutMax)		pi->Output = pi->OutMax;
    else 
    if (pi->Output < pi->OutMin)		pi->Output = pi->OutMin;

}
//===========================================================================================



//===========================================================================================
void Pi_Reset(Tpi * pi)
{

	pi->Err = 0.0f;
	pi->Up = 0.0f;
	pi->Ui = 0.0f;
	pi->Output = 0.0f;
	
}
