void Zi_Calc(Tzi *zi, float Uin) {
    const float epsilon = 0.001f; // Малое значение для сравнения чисел с плавающей точкой
    const float outputMax = 1000.0f; // Максимальное значение для интегратора (настройте под вашу систему)
    const float outputMin = -1000.0f; // Минимальное значение для интегратора (настройте под вашу систему)

    //--- Релейный элемент ---------------------------------------------------------------
    if (Uin > zi->Output + epsilon) {
        zi->UMax = SPEED_MAX; // Движение в положительном направлении
    } 
    else if (Uin < zi->Output - epsilon) {
        zi->UMax = -SPEED_MAX; // Движение в отрицательном направлении
    } 
    else {
        zi->UMax = 0.0f; // Остановка, если Uin и Output почти равны
    }

    //--- Интегратор --------------------------------------------------------------------
    zi->Output += zi->Ki * zi->UMax;

    //--- Ограничение выхода интегратора ------------------------------------------------
    if (zi->Output > outputMax) {
        zi->Output = outputMax;
    } 
    else if (zi->Output < outputMin) {
        zi->Output = outputMin;
    }
}

